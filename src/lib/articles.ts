export interface HubGroups {
  // Walkthroughs, research papers, tutorials, projects — Denis's own writing.
  handwritten: ArticleSummary[];
  // Daily digests and weekly trend reports.
  news: ArticleSummary[];
  // Standalone paper reviews (noindexed; listed compactly).
  reviews: ArticleSummary[];
}

// Split a hub's article list so the indexable, most distinctive content comes
// first and the noindexed review backlog does not dominate the page.
export function groupArticlesForHub(articles: ArticleSummary[]): HubGroups {
  const groups: HubGroups = { handwritten: [], news: [], reviews: [] };
  for (const article of articles) {
    if (article.type === 'Paper Review') groups.reviews.push(article);
    else if (getCategory(article.type) === NEWS_AND_TRENDS) groups.news.push(article);
    else groups.handwritten.push(article);
  }
  return groups;
}

// Related-article scoring. Pure tag overlap is a weak signal here — the
// canonical topics are broad enough that most of the corpus shares a tag —
// so ranking also rewards same-category affinity and recency. Weights keep
// tag overlap dominant: one extra shared tag (3) outweighs the category
// bonus (1.5) plus the maximum recency boost (1).
const RELATED_TAG_WEIGHT = 3;
const RELATED_CATEGORY_BONUS = 1.5;
// e-folding time of the recency boost: ~6 months old ≈ 0.37, ~1 year ≈ 0.13.
const RELATED_RECENCY_DECAY_DAYS = 180;

export function getRelatedArticles(
  currentSlug: string,
  currentTags: string[],
  limit = 3,
  articles: ArticleSummary[] = getAllArticles(),
): ArticleSummary[] {
  const currentTagSet = new Set(currentTags);
  const current = articles.find((a) => a.slug === currentSlug) ?? null;
  const currentCategory = current ? getCategory(current.type) : null;
  const currentIsHandwritten = current
    ? !isAutoGeneratedArticle({ type: current.type, title: current.title, date: current.date })
    : false;
  const currentIsIndexable = current ? isIndexableArticle(current) : true;
  const now = Date.now();

  return articles
    .filter((article) => {
      if (article.slug === currentSlug) return false;
      // Hand-written pieces never recommend the daily digest feed: with the
      // shared-tag corpus this dense, digests would otherwise crowd out
      // Denis's own related writing.
      if (currentIsHandwritten && getCategory(article.type) === NEWS_AND_TRENDS) return false;
      // Indexable pages never recommend noindexed paper reviews: each such
      // link spends an indexable page's equity on a URL that cannot rank, and
      // the day's digest already covers the review. Reviews may still
      // recommend each other.
      if (currentIsIndexable && !isIndexableArticle(article)) return false;
      return true;
    })
    .map((article) => {
      const sharedTagCount = article.tags.filter((tag) => currentTagSet.has(tag)).length;
      const categoryBonus =
        currentCategory !== null && getCategory(article.type) === currentCategory
          ? RELATED_CATEGORY_BONUS
          : 0;
      const ageDays = Math.max(0, (now - new Date(article.date).getTime()) / 86_400_000);
      const recencyBoost = Math.exp(-ageDays / RELATED_RECENCY_DECAY_DAYS);
      const score = sharedTagCount * RELATED_TAG_WEIGHT + categoryBonus + recencyBoost;
      return { article, sharedTagCount, score };
    })
    .filter((entry) => entry.sharedTagCount > 0)
    .sort((a, b) => {
      if (b.score !== a.score) {
        return b.score - a.score;
      }
      return new Date(b.article.date).getTime() - new Date(a.article.date).getTime();
    })
    .slice(0, limit)
    .map((entry) => entry.article);
}

