export interface MonthGroup {
  key: string; // 'YYYY-MM'
  label: string; // 'July 2026'
  articles: ArticleSummary[];
}

// Bucket a newest-first article list into contiguous month groups for dense
// chronological listings (the /news/ hub). Input order is preserved.
export function groupArticlesByMonth(articles: ArticleSummary[]): MonthGroup[] {
  const groups: MonthGroup[] = [];
  for (const article of articles) {
    const key = article.date.slice(0, 7);
    let group = groups[groups.length - 1];
    if (!group || group.key !== key) {
      const label = new Date(`${key}-01T00:00:00Z`).toLocaleDateString('en-US', {
        month: 'long',
        year: 'numeric',
        timeZone: 'UTC',
      });
      group = { key, label, articles: [] };
      groups.push(group);
    }
    group.articles.push(article);
  }
  return groups;
}

// Prev/next navigation is scoped to the current article's reader-facing
// category. Strict chronology across the whole corpus would sandwich
// hand-written pieces between daily digests, so instead each category forms
// its own chronological chain.
export function getAdjacentArticles(slug: string): { prev: ArticleSummary | null; next: ArticleSummary | null } {
  const articles = getAllArticles();
  const index = articles.findIndex((a) => a.slug === slug);
  if (index === -1) return { prev: null, next: null };

  const category = getCategory(articles[index].type);

  // Articles are sorted newest-first: prev (older) scans forward, next (newer)
  // scans backward, each stopping at the nearest article in the same category.
  let prev: ArticleSummary | null = null;
  for (let i = index + 1; i < articles.length; i++) {
    if (getCategory(articles[i].type) === category) {
      prev = articles[i];
      break;
    }
  }

  let next: ArticleSummary | null = null;
  for (let i = index - 1; i >= 0; i--) {
    if (getCategory(articles[i].type) === category) {
      next = articles[i];
      break;
    }
  }

  return { prev, next };
}

export interface NewsWeekCluster {
  // The weekly trend report that wraps up the window; null for a trend report
  // itself and for digests whose week has no report yet.
  weekly: ArticleSummary | null;
  // Daily digests inside the window, newest first, excluding the current one.
  dailies: ArticleSummary[];
}

const WEEK_WINDOW_DAYS = 6;
const DAY_MS = 86_400_000;

function dayNumber(date: string): number {
  return Math.floor(new Date(`${date}T00:00:00Z`).getTime() / DAY_MS);
}

// Same-week companions of a News & Trends article. A weekly report covers the
// seven days ending on its date; a daily digest belongs to the nearest weekly
// published within six days after it. Digests and weeklies otherwise only meet
// in the /news/ list and the prev/next chain, so this gives every issue a
// small, fully indexable cluster of in-links (daily <-> weekly, daily <->
// daily) rather than leaning on the hub alone.
export function getNewsWeekCluster(
  slug: string,
  articles: ArticleSummary[] = getAllArticles(),
): NewsWeekCluster {
  const current = articles.find((a) => a.slug === slug);
  if (!current || getCategory(current.type) !== NEWS_AND_TRENDS) {
    return { weekly: null, dailies: [] };
  }
  const news = articles.filter((a) => getCategory(a.type) === NEWS_AND_TRENDS);
  const day = dayNumber(current.date);

  let weekly: ArticleSummary | null = null;
  if (current.type !== 'Trend Report') {
    // Newest-first scan: distances shrink toward zero, so the last in-window
    // match before they turn negative is the nearest covering weekly.
    for (const candidate of news) {
      if (candidate.type !== 'Trend Report') continue;
      const distance = dayNumber(candidate.date) - day;
      if (distance < 0) break;
      if (distance <= WEEK_WINDOW_DAYS) weekly = candidate;
    }
  }

  const end = weekly ? dayNumber(weekly.date) : day;
  const start = end - WEEK_WINDOW_DAYS;
  const dailies = news.filter((a) => {
    if (a.type === 'Trend Report' || a.slug === slug) return false;
    const d = dayNumber(a.date);
    return d >= start && d <= end;
  });

  return { weekly, dailies };
}

