function pluralize(count: number, singular: string, plural = `${singular}s`): string {
  return `${count} ${count === 1 ? singular : plural}`;
}

function joinWithAnd(items: string[]): string {
  if (items.length <= 1) return items.join('');
  if (items.length === 2) return `${items[0]} and ${items[1]}`;
  return `${items.slice(0, -1).join(', ')}, and ${items[items.length - 1]}`;
}

function formatMonthYear(date: string): string {
  return new Date(`${date.slice(0, 7)}-01T00:00:00Z`).toLocaleDateString('en-US', {
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  });
}

const HANDWRITTEN_KIND_LABELS: Record<string, string> = {
  'Paper Walkthrough': 'paper walkthrough',
  'Research Paper': 'research paper',
  Tutorial: 'tutorial',
  Project: 'project',
};

// "7 paper walkthroughs, 2 research papers, and 1 tutorial", most common first.
function describeHandwrittenKinds(articles: ArticleSummary[]): string {
  const counts = new Map<string, number>();
  for (const article of articles) {
    const label = HANDWRITTEN_KIND_LABELS[article.type] ?? article.type.toLowerCase();
    counts.set(label, (counts.get(label) || 0) + 1);
  }
  return joinWithAnd(
    Array.from(counts.entries())
      .sort((a, b) => b[1] - a[1])
      .map(([label, count]) => pluralize(count, label)),
  );
}

// Landing copy for a tag hub. Apart from the three hand-written overrides,
// every sentence is derived from the hub's own articles (counts by kind,
// publication span, newest titles, co-occurring topics), so two hubs share
// only connective words. The previous fixed template made the intro of every
// non-override hub read identically, which is what "Crawled - currently not
// indexed" tends to punish on thin collection pages.
export function getTagLandingContent(tagName: string, articles: ArticleSummary[]): TagLandingContent {
  const relatedTagCounts = new Map<string, number>();
  for (const article of articles) {
    for (const tag of article.tags) {
      if (tag !== tagName) {
        relatedTagCounts.set(tag, (relatedTagCounts.get(tag) || 0) + 1);
      }
    }
  }
  const topRelatedTags = Array.from(relatedTagCounts.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, 3)
    .map(([tag]) => tag);

  const sorted = [...articles].sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
  const { handwritten, news, reviews } = groupArticlesForHub(sorted);
  const newest: ArticleSummary | undefined = sorted[0];
  const oldest: ArticleSummary | undefined = sorted[sorted.length - 1];

  const shortKinds: string[] = [];
  if (handwritten.length) shortKinds.push(pluralize(handwritten.length, 'hand-written piece'));
  if (news.length) shortKinds.push(pluralize(news.length, 'news issue'));
  if (reviews.length) shortKinds.push(pluralize(reviews.length, 'AI paper review'));

  const detailedKinds: string[] = [];
  if (handwritten.length) detailedKinds.push(describeHandwrittenKinds(handwritten));
  if (news.length) {
    const dailies = news.filter((a) => a.type === 'News Digest').length;
    const weeklies = news.length - dailies;
    detailedKinds.push(
      joinWithAnd([
        ...(dailies ? [pluralize(dailies, 'daily digest')] : []),
        ...(weeklies ? [pluralize(weeklies, 'weekly trend report')] : []),
      ]),
    );
  }
  if (reviews.length) detailedKinds.push(pluralize(reviews.length, 'standalone AI paper review'));

  const span = newest && oldest
    ? newest.date.slice(0, 7) === oldest.date.slice(0, 7)
      ? `in ${formatMonthYear(newest.date)}`
      : `between ${formatMonthYear(oldest.date)} and ${formatMonthYear(newest.date)}`
    : '';
  const coverage = newest
    ? `Published ${span}: ${detailedKinds.join('; ')}.`
    : `No articles are tagged ${tagName} yet.`;

  const override = tagLandingOverrides[tagName];
  const latestHandwritten: ArticleSummary | undefined = handwritten[0];
  const latestHandwrittenNote =
    latestHandwritten && latestHandwritten !== newest
      ? `; the latest hand-written piece is "${latestHandwritten.title}" (${latestHandwritten.date})`
      : '';
  const lead = override?.lead
    || (newest
      ? `This hub gathers everything tagged ${tagName}: ${joinWithAnd(shortKinds)}. The most recent is "${newest.title}" (${newest.date})${latestHandwrittenNote}.`
      : `Articles about ${tagName}.`);

  const overlap = topRelatedTags.length > 0
    ? `Here ${tagName} most often overlaps with ${joinWithAnd(topRelatedTags)}.`
    : '';
  const depth = handwritten.length > 0
    ? `The hand-written ${handwritten.length === 1 ? 'piece' : 'pieces'} — ${joinWithAnd(handwritten.slice(0, 3).map((a) => a.title))} — ${handwritten.length === 1 ? 'goes' : 'go'} deepest; the daily digests and weekly reports track new papers as they appear.`
    : 'Coverage of this topic comes from the daily digests and weekly trend reports, which summarize new papers as they appear.';
  const body = override?.body || [overlap, depth].filter(Boolean).join(' ');

  const startWith = [...handwritten.slice(0, 1), ...news.slice(0, 2)].slice(0, 2);
  const learnings = [
    topRelatedTags.length > 0
      ? `Related topics: ${joinWithAnd(topRelatedTags)}.`
      : 'Related topics: secure evaluation, validation, and operational hardening.',
    startWith.length > 0
      ? `Start with: ${joinWithAnd(startWith.map((a) => a.title))}.`
      : 'Start with the most recent write-up to understand current assumptions.',
    ...(reviews.length > 0
      ? [
          `${pluralize(reviews.length, 'standalone paper review is', 'standalone paper reviews are')} listed at the end; each is also summarized in the digest of its day.`,
        ]
      : []),
  ];

  // The newest issue's compact search title ("Topics — Series, Mon D, YYYY")
  // keeps the distinguishing words inside the ~158-character snippet.
  const metaDescription = newest
    ? `${pluralize(articles.length, 'article')} on ${tagName}: ${joinWithAnd(shortKinds)}. Latest: ${getSeoTitle(newest)}.`
    : `Articles on ${tagName}.`;

  return { lead, body, coverage, learnings, relatedTags: topRelatedTags, metaDescription };
}
