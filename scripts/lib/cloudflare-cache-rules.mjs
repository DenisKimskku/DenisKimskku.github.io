// Pure rule-builder / planner logic for scripts/ensure-cloudflare-cache-config.mjs.
// Kept free of I/O so tests/cloudflare-cache-config.test.mjs can exercise it.
//
// Why these rules exist (measured 2026-09-08, see the deploy-time comments in
// .github/workflows/deploy.yml): the origin (GitHub Pages) sends
// `cache-control: max-age=600` for everything, and Cloudflare's edge TTL for
// HTML/RSC/feeds is whatever the dashboard rule the owner created says — a
// value nobody in the repo can see. Every deploy purges the whole page set,
// so a long, explicit, code-managed edge TTL is safe: freshness comes from
// the purge, not from expiry. Browser TTL stays short so a visitor's browser
// never pins a stale page after a deploy.
//
// Cache Rules are stackable and "the value in the last matching rule wins"
// (https://developers.cloudflare.com/cache/how-to/cache-rules/order/), so
// appending these rules after any hand-made ones makes them authoritative
// for the settings they set without deleting anything the owner configured.

export const RULE_PREFIX = '[deniskim1 deploy]';
export const CACHE_PHASE = 'http_request_cache_settings';
export const DEFAULT_HOSTS = ['deniskim1.com', 'www.deniskim1.com'];

// Free plan allows 10 cache rules (https://developers.cloudflare.com/cache/how-to/cache-rules/).
export const FREE_PLAN_RULE_LIMIT = 10;

const DAY = 86400;
export const EDGE_TTL_CONTENT_SECONDS = 30 * DAY; // HTML, RSC .txt, XML, PDFs, images
export const EDGE_TTL_OG_SECONDS = 7 * DAY; // social cards are regenerated by every build; bound their staleness
export const EDGE_TTL_REDIRECT_SECONDS = 600;
export const EDGE_TTL_CLIENT_ERROR_SECONDS = 60; // a not-yet-deployed URL must not stick as a cached 404
export const BROWSER_TTL_CONTENT_SECONDS = 600; // matches today's origin max-age=600
export const BROWSER_TTL_OG_SECONDS = 3600;

// Path prefixes the content rule must NOT touch:
//  /_next/static/ — content-hashed, already covered by the owner's 1-year rule
//                   (observed `max-age=31536000`, which GitHub Pages never sends)
//  /og/           — has its own shorter rule below
//  /api/          — the deniskim1-ask Worker route (never cache API traffic)
//  /cdn-cgi/      — Cloudflare's own endpoints
export const CONTENT_RULE_EXCLUDED_PREFIXES = ['/_next/static/', '/og/', '/api/', '/cdn-cgi/'];

function hostExpression(hosts) {
  return `(http.host in {${hosts.map((host) => `"${host}"`).join(' ')}})`;
}

function excludePrefixes(prefixes) {
  return prefixes.map((prefix) => `not starts_with(http.request.uri.path, "${prefix}")`).join(' and ');
}

function statusCodeTtls(successTtl) {
  return [
    { status_code_range: { from: 200, to: 299 }, value: successTtl },
    { status_code_range: { from: 300, to: 399 }, value: EDGE_TTL_REDIRECT_SECONDS },
    { status_code_range: { from: 400, to: 499 }, value: EDGE_TTL_CLIENT_ERROR_SECONDS },
    // 0 == "no-cache" per https://developers.cloudflare.com/cache/how-to/cache-rules/settings/
    { status_code_range: { from: 500, to: 599 }, value: 0 },
  ];
}

export function buildDesiredRules({ hosts = DEFAULT_HOSTS } = {}) {
  const host = hostExpression(hosts);

  return [
    {
      description: `${RULE_PREFIX} site content: 30d edge TTL, purged by every deploy (HTML, RSC .txt, feeds, PDFs, images)`,
      expression: `${host} and ${excludePrefixes(CONTENT_RULE_EXCLUDED_PREFIXES)}`,
      action: 'set_cache_settings',
      enabled: true,
      action_parameters: {
        cache: true,
        edge_ttl: {
          mode: 'override_origin',
          default: EDGE_TTL_CONTENT_SECONDS,
          status_code_ttl: statusCodeTtls(EDGE_TTL_CONTENT_SECONDS),
        },
        browser_ttl: {
          mode: 'override_origin',
          default: BROWSER_TTL_CONTENT_SECONDS,
        },
      },
    },
    {
      description: `${RULE_PREFIX} /og/ social cards: 7d edge TTL (regenerated by every build; newest are purged)`,
      expression: `${host} and starts_with(http.request.uri.path, "/og/")`,
      action: 'set_cache_settings',
      enabled: true,
      action_parameters: {
        cache: true,
        edge_ttl: {
          mode: 'override_origin',
          default: EDGE_TTL_OG_SECONDS,
          status_code_ttl: statusCodeTtls(EDGE_TTL_OG_SECONDS),
        },
        browser_ttl: {
          mode: 'override_origin',
          default: BROWSER_TTL_OG_SECONDS,
        },
      },
    },
  ];
}

function stableStringify(value) {
  if (Array.isArray(value)) {
    return `[${value.map(stableStringify).join(',')}]`;
  }
  if (value && typeof value === 'object') {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`)
      .join(',')}}`;
  }
  return JSON.stringify(value);
}

function comparableRule(rule) {
  return stableStringify({
    expression: rule.expression,
    action: rule.action,
    enabled: rule.enabled !== false,
    action_parameters: rule.action_parameters,
  });
}

export function isManagedRule(rule) {
  return typeof rule?.description === 'string' && rule.description.startsWith(RULE_PREFIX);
}

// Decide what to do with the live entrypoint ruleset. Never proposes deleting
// or rewriting rules this repo did not create; a managed rule whose
// description no longer matches any desired rule is reported as an orphan.
export function planRuleChanges(existingRules, desiredRules, { ruleLimit = FREE_PLAN_RULE_LIMIT } = {}) {
  const existing = Array.isArray(existingRules) ? existingRules : [];
  const create = [];
  const update = [];
  const unchanged = [];

  for (const desired of desiredRules) {
    const match = existing.find((rule) => rule.description === desired.description);
    if (!match) {
      create.push(desired);
      continue;
    }

    if (comparableRule(match) === comparableRule(desired)) {
      unchanged.push({ id: match.id, description: desired.description });
    } else {
      update.push({ id: match.id, rule: desired });
    }
  }

  const desiredDescriptions = new Set(desiredRules.map((rule) => rule.description));
  const orphans = existing.filter((rule) => isManagedRule(rule) && !desiredDescriptions.has(rule.description));
  const foreign = existing.filter((rule) => !isManagedRule(rule));
  const resultingCount = existing.length + create.length;

  return {
    create,
    update,
    unchanged,
    orphans,
    foreign,
    resultingCount,
    overLimit: resultingCount > ruleLimit,
  };
}

// Cloudflare signals a token that lacks the needed scope with HTTP 403 (or
// 401) and error codes such as 10000 "Authentication error" / 9109
// "Unauthorized to access requested resource" / 1000-series auth errors.
const PERMISSION_ERROR_CODES = new Set([1000, 9103, 9106, 9109, 10000, 10001, 10014]);

export function isPermissionError(statusCode, body) {
  if (statusCode === 401 || statusCode === 403) {
    return true;
  }

  const errors = Array.isArray(body?.errors) ? body.errors : [];
  return errors.some((error) => PERMISSION_ERROR_CODES.has(Number(error?.code)));
}

export function describeCloudflareErrors(statusCode, body) {
  const errors = Array.isArray(body?.errors) ? body.errors : [];
  const details = errors.map((error) => `${error?.code ?? '?'}: ${error?.message ?? 'unknown error'}`).join('; ');
  return `HTTP ${statusCode}${details ? ` (${details})` : ''}`;
}

export function formatSeconds(seconds) {
  if (seconds % DAY === 0) return `${seconds / DAY} day(s)`;
  if (seconds % 3600 === 0) return `${seconds / 3600} hour(s)`;
  if (seconds % 60 === 0) return `${seconds / 60} minute(s)`;
  return `${seconds} s`;
}

// Printed whenever the API token cannot make a change, so the owner can do
// it by hand. Keep in sync with buildDesiredRules().
export function dashboardInstructions(desiredRules) {
  const lines = [
    'Owner action required (the API token cannot manage cache configuration):',
    '',
    'A. Extend the CF_API_TOKEN secret so future deploys can do this automatically:',
    '   dash.cloudflare.com > My Profile > API Tokens > (token used as CF_API_TOKEN) > Edit',
    '   add permissions:  Zone > Cache Rules > Edit   and   Zone > Zone Settings > Edit',
    '   (keep Zone > Cache Purge > Purge), Zone Resources: Include > deniskim1.com > Continue to summary > Update Token.',
    '   Docs: https://developers.cloudflare.com/cache/how-to/cache-rules/create-api/#required-api-token-permissions',
    '',
    'B. Or apply the same configuration by hand:',
    '   1. Caching > Tiered Cache > turn Tiered Cache ON and select "Smart Tiered Cache Topology".',
    '      Docs: https://developers.cloudflare.com/cache/how-to/tiered-cache/',
  ];

  desiredRules.forEach((rule, index) => {
    const edge = rule.action_parameters.edge_ttl;
    const browser = rule.action_parameters.browser_ttl;
    lines.push(
      `   ${index + 2}. Caching > Cache Rules > Create rule`,
      `      Rule name: ${rule.description}`,
      '      When incoming requests match: Custom filter expression > Edit expression, paste:',
      `        ${rule.expression}`,
      '      Cache eligibility: Eligible for cache',
      `      Edge TTL: "Ignore cache-control header and use this TTL" = ${formatSeconds(edge.default)}`,
      `        Status code TTL: 200-299 = ${formatSeconds(edge.default)}, 300-399 = ${formatSeconds(EDGE_TTL_REDIRECT_SECONDS)}, 400-499 = ${formatSeconds(EDGE_TTL_CLIENT_ERROR_SECONDS)}, 500-599 = no-cache`,
      `      Browser TTL: "Override origin and use this TTL" = ${formatSeconds(browser.default)}`,
      '      Place the rule LAST in the list (last matching rule wins), then Deploy.'
    );
  });

  lines.push('      Docs: https://developers.cloudflare.com/cache/how-to/cache-rules/settings/');
  return lines.join('\n');
}
