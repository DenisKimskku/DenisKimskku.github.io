#!/usr/bin/env node
// Static redirect stubs for legacy URLs.
//
// The site is a pure static export on GitHub Pages, so there is no server-side
// 301. For every legacy URL in src/data/redirects.json whose content still
// exists, this script writes out/<from>/index.html (or out/<from>.html for a
// file-style source) containing an instant meta refresh. Google's guidance:
// "Google Search interprets instant meta refresh redirects as permanent
// redirects" (https://developers.google.com/search/docs/crawling-indexing/301-redirects),
// and it lists meta refresh ahead of JavaScript redirects when server-side
// redirects are unavailable. The stub also carries a canonical link to the
// target, a JS location.replace for browsers, and a visible fallback link.
// No noindex is added: a noindex would contradict the redirect and could
// propagate onto the target.
//
// Safety rules (enforced here, unit-tested in tests/generate-redirects.test.mjs):
//   * never overwrite a real page in out/ (only a stub this script wrote before);
//   * never point at a target that does not exist in out/ (hard failure);
//   * never create a chain (a target may not itself be a redirect source).
//
// Usage: node scripts/generate-redirects.mjs [outDir]   (default: ./out)
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const SITE_URL = 'https://deniskim1.com';
export const STUB_MARKER = '<!-- redirect stub generated by scripts/generate-redirects.mjs -->';

const FILE_EXT_RE = /\.[a-z0-9]{1,5}$/i;

// Site paths are always absolute. A path without a file extension is a
// directory route on this site (trailingSlash: true), so it gets a trailing
// slash; file-style paths (legacy *.html) are kept verbatim.
export function normalizeSitePath(input) {
  if (typeof input !== 'string' || !input.startsWith('/')) {
    throw new Error(`Site path must start with "/": ${JSON.stringify(input)}`);
  }
  const [pathOnly] = input.split(/[?#]/, 1);
  const collapsed = pathOnly.replace(/\/{2,}/g, '/');
  if (collapsed.endsWith('/')) return collapsed;
  return FILE_EXT_RE.test(collapsed) ? collapsed : `${collapsed}/`;
}

// Where a site path is served from inside the export directory.
export function stubFileFor(sitePath) {
  const normalized = normalizeSitePath(sitePath);
  return normalized.endsWith('/')
    ? path.posix.join(normalized.slice(1), 'index.html')
    : normalized.slice(1);
}

export function isRedirectStub(html) {
  return typeof html === 'string' && html.includes(STUB_MARKER);
}

// A filesystem-backed existence check for site paths, plus stub detection.
export function createOutProbe(outDir) {
  const fileFor = (sitePath) => path.join(outDir, ...stubFileFor(sitePath).split('/'));
  return {
    // True when the URL already serves a real (non-stub) page.
    isRealPage(sitePath) {
      const file = fileFor(sitePath);
      if (!fs.existsSync(file)) return false;
      return !isRedirectStub(fs.readFileSync(file, 'utf8'));
    },
    // True when the URL serves anything at all (real page or stub).
    exists(sitePath) {
      return fs.existsSync(fileFor(sitePath));
    },
  };
}

// Expand `{ from: "/news/:slug/", to: "/writing/:slug/", slugs: "articles" }`
// into one explicit entry per article slug.
export function expandPatternRules(rules = [], slugSources = {}) {
  const expanded = [];
  for (const rule of rules) {
    const slugs = slugSources[rule.slugs];
    if (!Array.isArray(slugs)) {
      throw new Error(`patternRules: unknown slug source ${JSON.stringify(rule.slugs)} (have: ${Object.keys(slugSources).join(', ') || 'none'})`);
    }
    if (!rule.from?.includes(':slug') || !rule.to?.includes(':slug')) {
      throw new Error(`patternRules: both "from" and "to" must contain ":slug": ${JSON.stringify(rule)}`);
    }
    for (const slug of slugs) {
      expanded.push({
        from: rule.from.replaceAll(':slug', slug),
        to: rule.to.replaceAll(':slug', slug),
        source: `pattern ${rule.from}`,
      });
    }
  }
  return expanded;
}

// Pure planning step. `probe` answers isRealPage/exists for site paths.
// Returns the stubs to write, the sources skipped because they are live pages,
// and the errors that must fail the build.
export function buildRedirectPlan({ config, slugSources = {}, probe }) {
  const entries = [
    ...Object.entries(config.redirects || {}).map(([from, to]) => ({ from, to, source: 'redirects' })),
    ...expandPatternRules(config.patternRules, slugSources),
  ];

  const errors = [];
  const skipped = [];
  const byFrom = new Map();

  for (const entry of entries) {
    let from;
    let to;
    try {
      from = normalizeSitePath(entry.from);
      to = normalizeSitePath(entry.to);
    } catch (error) {
      errors.push(`${entry.source}: ${error.message}`);
      continue;
    }
    if (from === to) {
      errors.push(`${entry.source}: ${from} redirects to itself`);
      continue;
    }
    if (byFrom.has(from)) {
      if (byFrom.get(from).to !== to) {
        errors.push(`${from} is mapped to both ${byFrom.get(from).to} and ${to}`);
      }
      continue;
    }
    byFrom.set(from, { from, to, source: entry.source });
  }

  for (const entry of byFrom.values()) {
    if (byFrom.has(entry.to)) {
      errors.push(`${entry.from} -> ${entry.to} would chain into ${entry.to} -> ${byFrom.get(entry.to).to}`);
    }
  }

  const stubs = [];
  for (const entry of byFrom.values()) {
    if (probe.isRealPage(entry.from)) {
      skipped.push({ ...entry, reason: 'source is a live page' });
      continue;
    }
    if (!probe.exists(entry.to) || !probe.isRealPage(entry.to)) {
      errors.push(`${entry.from} -> ${entry.to}: target does not exist in the export`);
      continue;
    }
    stubs.push({ from: entry.from, to: entry.to, file: stubFileFor(entry.from), source: entry.source });
  }

  stubs.sort((a, b) => a.from.localeCompare(b.from));
  return { stubs, skipped, errors };
}

function escapeHtml(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

export function renderStub(from, to, siteUrl = SITE_URL) {
  const target = `${siteUrl}${normalizeSitePath(to)}`;
  const attr = escapeHtml(target);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
${STUB_MARKER}
<!-- Instant (0s) meta refresh: treated as a permanent redirect by Google Search.
     https://developers.google.com/search/docs/crawling-indexing/301-redirects -->
<meta http-equiv="refresh" content="0; url=${attr}">
<link rel="canonical" href="${attr}">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Redirecting to ${attr}</title>
<script>location.replace(${JSON.stringify(target)});</script>
</head>
<body>
<p>This page has moved to <a href="${attr}">${attr}</a>.</p>
</body>
</html>
`;
}

export function writeStubs(outDir, stubs, siteUrl = SITE_URL) {
  for (const stub of stubs) {
    const file = path.join(outDir, ...stub.file.split('/'));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, renderStub(stub.from, stub.to, siteUrl), 'utf8');
  }
}

export function loadSlugSources(articlesIndexPath) {
  const articles = JSON.parse(fs.readFileSync(articlesIndexPath, 'utf8'));
  return { articles: articles.map((article) => article.slug).filter(Boolean) };
}

function main() {
  const outDir = path.resolve(process.argv[2] || 'out');
  const configPath = path.join(process.cwd(), 'src', 'data', 'redirects.json');
  const articlesIndexPath = path.join(process.cwd(), 'src', 'data', 'articles-index.json');

  if (!fs.existsSync(path.join(outDir, 'index.html'))) {
    console.error(`generate-redirects: ${outDir} has no index.html - run next build first`);
    process.exit(1);
  }

  const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const slugSources = loadSlugSources(articlesIndexPath);
  const { stubs, skipped, errors } = buildRedirectPlan({ config, slugSources, probe: createOutProbe(outDir) });

  for (const entry of skipped) {
    console.warn(`generate-redirects: skipping ${entry.from} (${entry.reason})`);
  }
  if (errors.length > 0) {
    for (const error of errors) console.error(`generate-redirects: ${error}`);
    process.exit(1);
  }

  writeStubs(outDir, stubs);
  const explicit = stubs.filter((stub) => stub.source === 'redirects').length;
  console.log(`generate-redirects: wrote ${stubs.length} redirect stub(s) into ${path.relative(process.cwd(), outDir) || '.'} (${explicit} explicit, ${stubs.length - explicit} from pattern rules${skipped.length ? `, ${skipped.length} skipped` : ''})`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main();
}
